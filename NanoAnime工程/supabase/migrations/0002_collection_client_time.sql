-- NanoAnime番鉴 · 追番记录表 · 补两个「由客户端掌控」的列
--
-- 用法：打开 Supabase 后台 → 左侧 SQL Editor → New query → 把本文件整段粘进去 → Run。
-- 和 0001 一样，这个文件是**唯一的表结构出处**。
--
-- ⚠️ 为什么非要新加一列，不能直接用 0001 里那个 updated_at？
--
-- 因为 0001 的触发器（collection_touch_updated_at）会把 updated_at **强行改成
-- 服务器的当前时间**，客户端写什么进去都会被覆盖掉。
--
-- 平时这没问题——"服务器最后碰这行的时间"本来就是这个意思。
-- 但云端同步要问的是**另一个问题**：两台设备都改了同一部番，**哪一边的改动更新？**
-- 如果每次同步都会把时间戳顶成"现在"，那这个问题的答案就永远是"刚刚推上来的那条"：
--   设备 A 上是 10 月 3 日改的进度，设备 B 上是 10 月 5 日改的。
--   A 先上线同步 → 它的时间戳被刷成"现在" → B 后上线一看"云端比我的新" → 把 10 月 3 日那份盖到自己头上。
--   **用户 10 月 5 日的进度，就这么没了。**
--
-- 所以：`updated_at` 继续归服务器（记录"服务器最后动这行的时间"，谁也别改它），
-- 另外给一个 `client_updated_at` —— **触发器不碰它**，里面存的是"用户真正改动这条记录的时刻"。
-- 同步比大小一律比这一个。
--
-- `added_at` 同理：0001 里没有这一列，导致换设备后拿不回"加入追番的时间"，
-- /my 的排序（新加的排前面）就没了依据。

-- ---------------------------------------------------------------------------
-- 加列
-- ---------------------------------------------------------------------------
-- ⚠️ 用 if not exists：这个文件可以重复跑，不会因为"列已经存在"而中途失败。

alter table public.collection
  add column if not exists client_updated_at timestamptz not null default now();

alter table public.collection
  add column if not exists added_at timestamptz;

-- 万一 0001 之后已经有人写过行（目前没有，但别假设），给它们补一个加入时间，
-- 免得这些行在 /my 上排到最后面去。
update public.collection set added_at = updated_at where added_at is null;

-- ---------------------------------------------------------------------------
-- 把「为什么」写进数据库本身
-- ---------------------------------------------------------------------------
-- 免得将来有人看着两个时间戳发懵，顺手把 client_updated_at 删了、或者"统一"成一个。

comment on column public.collection.updated_at is
  '服务器最后改动这一行的时刻，由触发器 collection_touch_updated_at 维护。⚠️ 不要把云端同步的冲突判断建在这一列上——它会被刷成"现在"，比不出哪边的改动更新。要比请用 client_updated_at。';

comment on column public.collection.client_updated_at is
  '用户真正改动这条追番记录的时刻（客户端写入）。合并冲突时以它为准：大的赢。⚠️ 触发器刻意不碰这一列，改动 0001 的触发器时也别把它加进去。';

comment on column public.collection.added_at is
  '加入追番的时刻。用来在换设备后仍然保持「新加的排前面」这个顺序。';

-- ---------------------------------------------------------------------------
-- 不用改的东西（写出来免得有人以为漏了）
-- ---------------------------------------------------------------------------
-- - **RLS 策略一行都不用改**：策略是**按行**判断的（这一行是不是你的），
--   不是按列。新加的列自动被现有的四条策略覆盖。
-- - **触发器一行都不用改**：它只设置 updated_at，本来就没碰新列。
-- - **权限不用重新 grant**：0001 里的 grant 是整表级的。
